-- RiesgosRA - esquema de pruebas de autenticacion en PostgreSQL
-- Reconstruido a partir de la metadata/capturas compartidas en el chat.
-- Ejecutar SOLO dentro de una base vacia (por ejemplo, riesgos_ra).
-- No contiene DROP ni elimina datos. Si las tablas ya existen, detenerse y revisar antes.

BEGIN;

CREATE TABLE public.roles (
    id_rol integer GENERATED BY DEFAULT AS IDENTITY,
    nombre_rol character varying(30),
    CONSTRAINT pk_roles PRIMARY KEY (id_rol)
);

CREATE TABLE public.permisos (
    id_permiso integer GENERATED BY DEFAULT AS IDENTITY,
    nombre_permiso character varying(50),
    CONSTRAINT pk_permisos PRIMARY KEY (id_permiso)
);

CREATE TABLE public.usuarios (
    id_usuario integer GENERATED BY DEFAULT AS IDENTITY,
    identificador_usuario character varying(100),
    contrasena_hash character varying(255),
    id_rol integer NOT NULL,
    CONSTRAINT pk_usuarios PRIMARY KEY (id_usuario),
    CONSTRAINT fk_usuarios_rol FOREIGN KEY (id_rol)
        REFERENCES public.roles (id_rol)
);

CREATE TABLE public.roles_permisos (
    id_rol integer NOT NULL,
    id_permiso integer NOT NULL,
    CONSTRAINT pk_roles_permisos PRIMARY KEY (id_rol, id_permiso),
    CONSTRAINT fk_roles_permisos_rol FOREIGN KEY (id_rol)
        REFERENCES public.roles (id_rol),
    CONSTRAINT fk_roles_permisos_permiso FOREIGN KEY (id_permiso)
        REFERENCES public.permisos (id_permiso)
);

CREATE TABLE public.sesiones (
    id_sesion integer GENERATED BY DEFAULT AS IDENTITY,
    id_usuario integer NOT NULL,
    token_hash character varying(64),
    fecha_creacion timestamp without time zone NOT NULL,
    fecha_expiracion timestamp without time zone NOT NULL,
    estado bit(1) NOT NULL,
    CONSTRAINT pk_sesiones PRIMARY KEY (id_sesion),
    CONSTRAINT fk_sesiones_usuario FOREIGN KEY (id_usuario)
        REFERENCES public.usuarios (id_usuario)
);

COMMIT;
